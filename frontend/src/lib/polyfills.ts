/**
 * Полифилл Node-глобалов для браузера.
 *
 * @ton/core (через @tonconnect/ui-react) ожидает глобальный Buffer —
 * он нужен ему для сборки BOC при формировании транзакции. В Node он есть
 * всегда, в браузере — никогда, а Vite (в отличие от Webpack) его не
 * подставляет автоматически.
 *
 * Без этого файла страница падает ДО отрисовки: TonConnectUIProvider стоит
 * в самом корне (main.tsx), поэтому исключение при инициализации кошелька
 * рвёт monтирование всего приложения, а не только экран оплаты — витрина
 * не открывается вообще, с чистым экраном и ReferenceError в консоли.
 *
 * Импортировать этот файл нужно ПЕРВОЙ строкой в main.tsx, до всех
 * остальных импортов — иначе к моменту, когда до него дойдёт очередь,
 * TON-библиотека уже попытается прочитать Buffer и упадёт.
 */
import { Buffer } from 'buffer'

// globalThis типизирован через lib.dom, где Buffer не объявлен (это
// Node-тип) — приводим один раз, а не подавляем ошибку на каждой строке.
const globalWithBuffer = globalThis as unknown as { Buffer?: typeof Buffer }

if (!globalWithBuffer.Buffer) {
    globalWithBuffer.Buffer = Buffer
}
